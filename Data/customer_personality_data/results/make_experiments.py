def f(x, d=3):
    return "–" if pd.isna(x) else f"{x:.{d}f}"


def sig(r):
    """Verdict of one paired comparison: corrected t (Nadeau-Bengio) is the main test, Wilcoxon is the optimistic one."""
    if pd.isna(r.p_nb):
        return "reference"
    if r.p_nb < 0.05:
        return "significant (corrected p < 0.05)"
    return "Wilcoxon p < 0.05 only (weak)" if r.p_wilcoxon < 0.05 else "no difference"


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(str(v).replace("|", "\\|") for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(out)


def variant_table(tag, task, label):
    d = R(f"{tag}_{task}.csv")
    rows = [dict(model=r.model.split(" | ", 1)[-1] if " | " in r.model else r.model, mean=f(r["mean"]), sd=f(r["std"]),
                 diff_vs_reference=f(r.mean_diff, 3) if pd.notna(r.p_nb) else "–",
                 CI95=("[" + f(r.ci_lo) + ", " + f(r.ci_hi) + "]") if pd.notna(r.p_nb) else "–",
                 p_corrected=f(r.p_nb), p_wilcoxon=f(r.p_wilcoxon), verdict=sig(r)) for _, r in d.iterrows()]
    return md_table(pd.DataFrame(rows).rename(columns={"mean": f"mean {label}", "sd": "std"}))


def gate_table(task, label):
    g = R(f"gate_{task}.csv")
    rows = [dict(curriculum=r.curriculum, extracurricular=r.extracurricular.replace("FT-Transformer-lite | ", "FT | ").replace("NAM (log1p + Huber) | ", "NAM | "),
                 **{f"{label} cur.": f(r.mean_a), f"{label} extra.": f(r.mean_b)}, gap=f(r.mean_diff, 3),
                 CI95="[" + f(r.ci_lo) + ", " + f(r.ci_hi) + "]", p_corrected=f(r.p_nb), p_wilcoxon=f(r.p_wilcoxon)) for _, r in g.iterrows()]
    return md_table(pd.DataFrame(rows))


def ranking(task, label, top=12):
    s = R(f"summary_{task}_all.csv")
    s = s[~s["name"].str.contains("scratch")].head(top)
    return md_table(pd.DataFrame({"model": s["name"], f"mean {label}": s["mean"].map(f), "std": s["std"].map(f), "tier": s["tier"]}))


def single_split(task, label):
    led = pd.read_csv(os.path.join(ROOT, "results", "ledger.csv"))
    m = "f1" if task == "classification" else "r2"
    d = led[(led.task == task) & (led.scheme == "single") & (led.version == "V6_0")].sort_values(m, ascending=False).head(6)
    return md_table(pd.DataFrame({"model": d["model"], f"{label} (448/443 test rows)": d[m].map(f)}))


def best_of(task, tier):
    s = R(f"summary_{task}_all.csv")
    s = s[(~s["name"].str.contains("scratch")) & (s.tier == tier)].iloc[0]
    return s["name"], s["mean"]


